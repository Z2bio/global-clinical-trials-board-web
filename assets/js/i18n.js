export function t(language, key, params = {}) {
  const lang = normalizeLanguage(language)
  const template = TEXT[lang][key] ?? TEXT[DEFAULT_LANGUAGE][key] ?? key
  return Object.entries(params).reduce((value, [name, replacement]) => (
    value.replaceAll(`{${name}}`, String(replacement ?? ''))
  ), template)
}

export function label(language, group, code, fallback = '') {
  const lang = normalizeLanguage(language)
  return LABELS[group]?.[lang]?.[code] || LABELS[group]?.[DEFAULT_LANGUAGE]?.[code] || fallback || code || t(lang, 'unknown')
}

export function statusMeta(language, code) {
  const existing = LABELS.status?.[normalizeLanguage(language)]?.[code || 'UNKNOWN']
    || LABELS.status?.[normalizeLanguage(language)]?.UNKNOWN
    || LABELS.status?.[DEFAULT_LANGUAGE]?.UNKNOWN
  const [statusLabel, plain] = existing
  return { label: statusLabel, plain }
}

export function phaseLabel(language, phases = []) {
  if (!Array.isArray(phases) || phases.length === 0) return language === 'en' ? 'Phase not disclosed' : '分期未公开'
  return phases.map((item) => label(language, 'phase', item, item)).join(' / ')
}

export function localizeUnknown(language, value) {
  const raw = String(value ?? '').trim()
  if (!raw || raw === '未公开' || raw === 'NCT 编号未公开' || raw === '人数类型未公开' || raw === '分期未公开') return t(language, 'unknown')
  return raw
}

export function languageFromStorage() {
  try { return normalizeLanguage(localStorage.getItem(LANGUAGE_KEY)) } catch { return DEFAULT_LANGUAGE }
}

export function saveLanguage(language) {
  try { localStorage.setItem(LANGUAGE_KEY, normalizeLanguage(language)) } catch { /* ignore */ }
}
